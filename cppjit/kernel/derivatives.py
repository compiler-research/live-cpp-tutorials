"""The derivatives Clad writes for the notebooks, generated in the session.

The kernel's compiler carries Clad: in the browser kernel and in the cppjit wheel this repository releases (CppInterOp
built with the Clad plugin). `load(name)` makes the requests that the notebooks need and aliases the generated functions
into namespace clad_generated; `code(name)` returns the source Clad generated, as text.
"""
import sys
import cppjit

# name -> (the header, Clad's requests, the generated functions the notebooks call)
REQUESTS = {
    "logistic_step": ("logistic_step.h",
                      'auto _clad_ls_dr = clad::differentiate(logistic_step<double>, "r");\n'
                      'auto _clad_ls_grad = clad::gradient(logistic_step<double>);',
                      ["logistic_step_darg1", "logistic_step_grad"], ["_clad_ls_dr", "_clad_ls_grad"]),
    "ball": ("ball.h", 'auto _clad_loss = clad::gradient(loss, "p");', ["loss_grad_0"], ["_clad_loss"]),
    "twin": ("twin.h", 'auto _clad_oxy = clad::gradient(oxygen_after, "cons, o_edge");', ["oxygen_after_grad_2_3"], ["_clad_oxy"]),
}
_loaded = set()
_plugin = None


def clad_in_kernel():
    """True when the interpreter's Clang carries the Clad plugin (the headers alone generate nothing). Probed once."""
    global _plugin
    if _plugin is None:
        cppjit.cppdef('#include "clad/Differentiator/Differentiator.h"')
        # Declared silently: without the plugin Clad's header stops on its own static_assert.
        ok = cppjit.gbl.Cpp.Declare('double _clad_probe(double x) { return x * x; }\n'
                                    'auto _clad_probe_d = clad::differentiate(_clad_probe, "x");', True) == 0
        _plugin = ok and getattr(cppjit.gbl, "_clad_probe_darg0", None) is not None
    return _plugin


def load(name):
    """Generate the derivatives of `name` and expose them as clad_generated::<function>."""
    if name in _loaded:
        return
    header, requests, functions, objects = REQUESTS[name]
    if not clad_in_kernel():
        raise RuntimeError("this cppjit has no Clad plugin; install the cppjit wheel of the live-cpp-tutorials release "
                           "(README.md), or open the notebook in the browser")
    cppjit.cppdef(f'#include "{header}"\n{requests}')
    cppjit.cppdef("namespace clad_generated { " + " ".join(f"using ::{f};" for f in functions) + " }")
    # getCode() of each request, reachable from Python through a plain function (a CladFunction object is not bindable)
    cppjit.cppdef(f'#include <string>\nstd::string _clad_code_{name}() {{ return '
                  + ' + "\\n" + '.join(f"std::string({o}.getCode())" for o in objects) + '; }')
    _loaded.add(name)
    print(f"[clad] {', '.join(functions)}: generated by the Clad inside this kernel", file=sys.stderr)


def code(name):
    """The source Clad generated for `name`, as Clad prints it."""
    load(name)
    return str(getattr(cppjit.gbl, f"_clad_code_{name}")())
